import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// A `.d.css.ts` beside each CSS module naming its classes, so `styles.title` type-checks (a typo
// is an error) under noPropertyAccessFromIndexSignature. Generated, gitignored.

function moduleFiles(dir: string): string[] {
    return readdirSync(dir).flatMap((entry) => {
        const path = join(dir, entry);
        if (statSync(path).isDirectory()) return moduleFiles(path);
        return entry.endsWith(".module.css") ? [path] : [];
    });
}

export function classNames(css: string): readonly string[] {
    const bare = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/url\([^)]*\)/g, "");
    const names = new Set<string>();
    for (const match of bare.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)) {
        if (match[1] !== undefined) names.add(match[1]);
    }
    return [...names].sort();
}

export function writeCssTypes(srcDir: string): void {
    for (const file of moduleFiles(srcDir)) {
        const fields = classNames(readFileSync(file, "utf8"))
            .map((name) => `    readonly ${JSON.stringify(name)}: string;`)
            .join("\n");
        writeFileSync(
            file.replace(/\.css$/, ".d.css.ts"),
            `// Generated by web/dev/css-types.ts.\ndeclare const classes: {\n${fields}\n};\nexport default classes;\n`,
        );
    }
}
