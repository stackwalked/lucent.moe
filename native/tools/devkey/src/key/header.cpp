#include "key/header.hpp"

#include <cstddef>
#include <filesystem>
#include <format>
#include <span>
#include <string>
#include <system_error>
#include <vector>

#include <lucent/crypto/crypto.hpp>
#include <lucent/os/file.hpp>

namespace lucent::devkey {
namespace {

constexpr usize bytes_per_line = 8;

auto header_text(const crypto::public_key& key) -> std::string {
    std::string bytes;
    for (usize index = 0; const std::byte part : key) {
        const bool is_line_start = index % bytes_per_line == 0;
        bytes += std::format(
            "{}std::byte{{0x{:02x}}},", is_line_start ? "\n    " : " ", static_cast<u8>(part)
        );
        ++index;
    }
    return std::format(
        "// Generated by devkey from this machine's dev seed (%LOCALAPPDATA%\\lucent\\dev); do not "
        "edit.\n"
        "// It lives in the build tree only: never in git, never in a release build.\n"
        "#pragma once\n"
        "\n"
        "#include <cstddef>\n"
        "\n"
        "#include <lucent/crypto/crypto.hpp>\n"
        "\n"
        "namespace lucent::devkey {{\n"
        "\n"
        "inline constexpr crypto::public_key public_key{{{}\n"
        "}};\n"
        "\n"
        "}}\n",
        bytes
    );
}

auto as_text(std::span<const std::byte> bytes) -> std::string {
    std::string text;
    text.reserve(bytes.size());
    for (const std::byte part : bytes) {
        text.push_back(static_cast<char>(part));
    }
    return text;
}

}

auto write_public_key_header(const std::filesystem::path& header, const crypto::public_key& key)
    -> result<void> {
    const std::string text = header_text(key);
    const result<std::vector<std::byte>> existing = os::read_file(header);
    if (existing && as_text(*existing) == text) {
        return {};
    }
    std::error_code failure;
    std::filesystem::create_directories(header.parent_path(), failure);
    return os::write_file(header, std::as_bytes(std::span{text}));
}

}
